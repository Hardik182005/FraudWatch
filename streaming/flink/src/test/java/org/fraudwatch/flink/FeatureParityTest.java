package org.fraudwatch.flink;

import com.fasterxml.jackson.databind.JsonNode;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Test;

import java.io.BufferedReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assertions.fail;

/**
 * Runs the Flink feature port over tests/streaming/fixtures/parity_fixture.jsonl (generated by
 * tests/streaming/make_fixture.py with fwcore) and asserts exact (bitwise for doubles) equality with
 * expected_features.jsonl. Records go through the same deserializer/validator used by the job.
 */
class FeatureParityTest {

    static Path fixtureDir() {
        String p = System.getProperty("fixture.dir", "../../tests/streaming/fixtures");
        return Paths.get(p);
    }

    static List<JsonNode> readJsonl(Path p) throws Exception {
        List<JsonNode> out = new ArrayList<>();
        try (BufferedReader r = Files.newBufferedReader(p, StandardCharsets.UTF_8)) {
            String line;
            while ((line = r.readLine()) != null) {
                if (!line.isBlank()) {
                    out.add(EventValidator.MAPPER.readTree(line));
                }
            }
        }
        return out;
    }

    @Test
    void rawFeaturesMatchFwcoreReference() throws Exception {
        Path dir = fixtureDir();
        Assumptions.assumeTrue(Files.exists(dir.resolve("parity_fixture.jsonl")), "fixture not found at " + dir.toAbsolutePath());
        List<JsonNode> steps = readJsonl(dir.resolve("parity_fixture.jsonl"));
        List<JsonNode> expected = readJsonl(dir.resolve("expected_features.jsonl"));
        Map<Long, JsonNode> expBySeq = new HashMap<>();
        for (JsonNode e : expected) {
            expBySeq.put(e.get("seq").longValue(), e);
        }

        Map<String, Features.AccountState> states = new HashMap<>();
        int compared = 0, late = 0, invalid = 0, maxCount1h = 0;
        long offset = 0;
        for (JsonNode step : steps) {
            String op = step.get("op").textValue();
            if ("invalid".equals(op)) {
                Records.InputRecord r = InputDeserializer.toInput(step.get("raw").textValue().getBytes(StandardCharsets.UTF_8), 0, offset++, 0L, 0L);
                assertEquals(Records.KIND_INVALID, r.kind, "invalid record accepted: " + step);
                invalid++;
                continue;
            }
            if (!"txn".equals(op)) {
                continue;
            }
            byte[] bytes = EventValidator.MAPPER.writeValueAsBytes(step.get("event"));
            Records.InputRecord in = InputDeserializer.toInput(bytes, 0, offset++, 0L, 0L);
            assertEquals(Records.KIND_TXN, in.kind, "valid txn rejected: " + in.error);
            if (!in.targetsFlink) {
                continue;
            }
            boolean isLate = step.get("late").booleanValue();
            Features.AccountState st = states.computeIfAbsent(in.stateKey(), k -> new Features.AccountState());
            Features.RawFeatures raw = Features.computeRaw(st, in.eventTime, in.amount);
            if (!isLate) {
                Features.update(st, in.eventTime, in.amount);
            } else {
                late++;
            }
            assertTrue(st.entryTs.length <= Features.MAX_ENTRIES);
            JsonNode exp = expBySeq.get(step.get("event").get("seq").longValue()).path("engines").path("flink");
            assertTrue(!exp.isMissingNode(), "no expectation for seq " + step.get("event").get("seq"));
            assertEquals(exp.get("late").booleanValue(), isLate);
            assertRawEquals(exp.get("raw"), raw, in.eventId);
            maxCount1h = (int) Math.max(maxCount1h, raw.priorCount1h);
            compared++;
        }
        System.out.printf("FeatureParityTest: compared=%d late=%d invalid=%d max_prior_count_1h=%d%n",
                compared, late, invalid, maxCount1h);
        assertTrue(compared > 1000);
        assertEquals(500, maxCount1h, "fixture should exercise the MAX_ENTRIES cap");
    }

    static void assertRawEquals(JsonNode e, Features.RawFeatures a, String id) {
        exactDouble(e, "amount", a.amount, id);
        exactLong(e, "prior_count_60s", a.priorCount60s, id);
        exactLong(e, "prior_count_10m", a.priorCount10m, id);
        exactLong(e, "prior_count_1h", a.priorCount1h, id);
        exactDouble(e, "prior_amount_sum_1h", a.priorAmountSum1h, id);
        exactLong(e, "small_count_10m", a.smallCount10m, id);
        nullableDouble(e, "secs_since_last", a.secsSinceLast, id);
        exactLong(e, "prior_count_total", a.priorCountTotal, id);
        nullableDouble(e, "prior_mean_amount", a.priorMeanAmount, id);
        nullableDouble(e, "amount_ratio", a.amountRatio, id);
    }

    static void exactLong(JsonNode e, String f, long actual, String id) {
        if (!e.get(f).isIntegralNumber() || e.get(f).longValue() != actual) {
            fail(id + " " + f + ": expected " + e.get(f) + " got " + actual);
        }
    }

    static void exactDouble(JsonNode e, String f, double actual, String id) {
        double exp = e.get(f).doubleValue();
        if (Double.doubleToLongBits(exp) != Double.doubleToLongBits(actual)) {
            fail(id + " " + f + ": expected " + e.get(f) + " got " + actual);
        }
    }

    static void nullableDouble(JsonNode e, String f, Double actual, String id) {
        if (e.get(f).isNull() || actual == null) {
            if (!(e.get(f).isNull() && actual == null)) {
                fail(id + " " + f + ": expected " + e.get(f) + " got " + actual);
            }
            return;
        }
        exactDouble(e, f, actual, id);
    }

    @Test
    void validatorMatchesPythonRules() {
        String base = "{\"schema_version\":\"1.1\",\"kind\":\"txn\",\"event_id\":\"e\",\"demo_session_id\":\"s\",\"run_id\":\"r\","
                + "\"seq\":1,\"account_id\":\"a\",\"event_time\":1,\"produced_at\":1,\"amount\":10.5,\"product_cd\":\"W\","
                + "\"card_network\":\"visa\",\"card_type\":\"debit\",\"email_domain\":\"gmail.com\",\"device_type\":\"mobile\","
                + "\"has_identity\":true,\"target_engines\":[\"flink\"]}";
        assertEquals(null, err(base));
        assertEquals("missing field: seq", err(base.replace("\"seq\":1,", "")));
        assertEquals("seq must be an integer", err(base.replace("\"seq\":1", "\"seq\":true")));
        assertEquals("seq has wrong type", err(base.replace("\"seq\":1", "\"seq\":1.0")));
        assertEquals("amount out of range", err(base.replace("10.5", "0")));
        assertEquals("amount out of range", err(base.replace("10.5", "NaN")));
        assertEquals(null, err(base.replace("10.5", "true"))); // Python bool is an int subclass
        assertEquals("invalid target_engines", err(base.replace("[\"flink\"]", "[]")));
        assertEquals("invalid target_engines", err(base.replace("[\"flink\"]", "[\"flink\",\"storm\"]")));
        assertEquals("unsupported schema_version", err(base.replace("\"1.1\"", "\"2.0\"")));
        assertEquals("kind must be txn or heartbeat", err(base.replace("\"txn\"", "\"x\"")));
        assertEquals("event must be a JSON object", err("[1,2]"));
        assertEquals("identifier too long", err(base.replace("\"account_id\":\"a\"", "\"account_id\":\"" + "x".repeat(65) + "\"")));
        assertEquals(null, err("{\"kind\":\"heartbeat\",\"event_time\":5,\"produced_at\":6}"));
        assertEquals("heartbeat.event_time must be an integer epoch ms", err("{\"kind\":\"heartbeat\",\"event_time\":5.0,\"produced_at\":6}"));
        assertTrue(err("{\"a\":1} trailing").startsWith("invalid JSON"));
    }

    static String err(String json) {
        try {
            EventValidator.decode(json.getBytes(StandardCharsets.UTF_8));
            return null;
        } catch (EventValidator.ValidationException e) {
            return e.getMessage();
        }
    }
}
